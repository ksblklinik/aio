<?php

declare(strict_types=1);

namespace Tests\Unit;

use App\Modules\Inventory\Contracts\InventoryRegistryInterface;
use App\Modules\Inventory\Services\InventoryService;
use Core\Database\Connection;
use Core\Database\Migrator;
use Core\Database\TenantContext;
use Core\Sequence\SequenceManager;
use PHPUnit\Framework\TestCase;
use RuntimeException;

class InventoryModuleTest extends TestCase
{
    private Connection $db;
    private Migrator $migrator;
    private TenantContext $tenantContext;
    private InventoryService $service;

    protected function setUp(): void
    {
        parent::setUp();

        $this->db = new Connection('sqlite::memory:');
        $this->migrator = new Migrator($this->db);
        $this->migrator->runMigrationsFrom(__DIR__ . '/../../database/migrations');

        $this->tenantContext = TenantContext::getInstance();
        $this->tenantContext->clear();

        $container = \Core\Container::getInstance();
        $container->instance(Connection::class, $this->db);
        $container->instance(TenantContext::class, $this->tenantContext);
        $container->instance(SequenceManager::class, new SequenceManager($this->db));

        // Buat tenant 1 & 2
        $this->db->statement("INSERT INTO tenants (id, name, slug) VALUES (1, 'Klinik Sehat', 'klinik')");
        $this->db->statement("INSERT INTO tenants (id, name, slug) VALUES (2, 'Bengkel Maju', 'bengkel')");

        $this->service = new InventoryService($this->db, $this->tenantContext);
        $container->instance(InventoryRegistryInterface::class, $this->service);
    }

    protected function tearDown(): void
    {
        $this->tenantContext->clear();
        parent::tearDown();
    }

    public function testCreateGoodsItemWithAutoGeneratedCodeAndInitialStock(): void
    {
        $this->tenantContext->setTenantId('1');

        $units = $this->service->listUnits();
        $this->assertNotEmpty($units);
        $boxUnit = $units[1]['id']; // BOX

        $itemId = $this->service->createItem([
            'name' => 'Amoxicillin 500mg',
            'sku' => 'MED-AMX-500',
            'barcode' => '8991234567890',
            'type' => 'goods',
            'unit_id' => $boxUnit,
            'cost_price' => 45000.0,
            'selling_price' => 60000.0,
            'initial_stock' => 100.0,
            'min_stock_alert' => 15.0,
        ]);

        $this->assertGreaterThan(0, $itemId);

        $item = $this->service->getItem($itemId);
        $this->assertNotNull($item);
        $this->assertSame('Amoxicillin 500mg', $item['name']);
        $this->assertStringStartsWith('ITM/', $item['code']);
        $this->assertSame('MED-AMX-500', $item['sku']);
        $this->assertSame('8991234567890', $item['barcode']);
        $this->assertEquals(100.0, $item['current_stock']);
        $this->assertEquals(100.0, $this->service->getStock($itemId));
        $this->assertSame('BOX', $item['unit_code']);

        // Verifikasi mutasi saldo awal otomatis tercatat di inventory_movements
        $history = $this->service->getStockMovementHistory($itemId);
        $this->assertCount(1, $history);
        $this->assertSame('in', $history[0]['type']);
        $this->assertEquals(100.0, $history[0]['quantity']);
        $this->assertSame('Saldo Awal Item', $history[0]['notes']);
    }

    public function testCreateServiceItemDoesNotTrackPhysicalInventory(): void
    {
        $this->tenantContext->setTenantId('1');

        $itemId = $this->service->createItem([
            'name' => 'Jasa Konsultasi Dokter Umum',
            'type' => 'service',
            'cost_price' => 0.0,
            'selling_price' => 75000.0,
        ]);

        $item = $this->service->getItem($itemId);
        $this->assertNotNull($item);
        $this->assertSame('service', $item['type']);
        $this->assertSame(0, $item['track_inventory']);

        // Layanan selalu tersedia terlepas dari kuantitas
        $this->assertTrue($this->service->checkAvailability($itemId, 999.0));

        // Mencoba mutasi fisik pada layanan harus melempar exception
        $this->expectException(RuntimeException::class);
        $this->expectExceptionMessage("Item bertipe 'service' atau non-inventory tidak mengelola mutasi stok fisik");
        $this->service->recordStockMovement($itemId, 5.0, 'in');
    }

    public function testDefaultUnitsAutoSeeding(): void
    {
        $this->tenantContext->setTenantId('1');

        $units = $this->service->listUnits();
        $this->assertGreaterThanOrEqual(9, count($units));

        $codes = array_column($units, 'code');
        $this->assertContains('PCS', $codes);
        $this->assertContains('BOX', $codes);
        $this->assertContains('STRIP', $codes);
        $this->assertContains('BTL', $codes);
        $this->assertContains('JAM', $codes);
    }

    public function testStockMovementInAndOutWithInsufficientStockGuard(): void
    {
        $this->tenantContext->setTenantId('1');

        $itemId = $this->service->createItem([
            'name' => 'Paracetamol Sirup 60ml',
            'type' => 'goods',
            'initial_stock' => 20.0,
        ]);

        // 1. Tambah stok masuk (+30 botol)
        $this->service->recordStockMovement($itemId, 30.0, 'in', 'Pembelian dari PBF');
        $this->assertEquals(50.0, $this->service->getStock($itemId));

        // 2. Coba pengeluaran melebihi stok (minta 60 botol padahal sisa 50) -> Harus throw Exception
        try {
            $this->service->recordStockMovement($itemId, 60.0, 'out', 'Penjualan Resep');
            $this->fail('Harus gagal jika pengeluaran melebihi stok fisik');
        } catch (RuntimeException $e) {
            $this->assertStringContainsString('Stok tidak mencukupi', $e->getMessage());
        }

        // Sisa stok harus tetap 50
        $this->assertEquals(50.0, $this->service->getStock($itemId));

        // 3. Pengeluaran yang sah (15 botol) -> Berhasil
        $this->service->recordStockMovement($itemId, 15.0, 'out', 'Penjualan Resep 001');
        $this->assertEquals(35.0, $this->service->getStock($itemId));
    }

    public function testStockAdjustmentAndOpname(): void
    {
        $this->tenantContext->setTenantId('1');

        $itemId = $this->service->createItem([
            'name' => 'Kapas Medis 500gr',
            'type' => 'goods',
            'initial_stock' => 10.0,
        ]);

        // Opname fisik menemukan ada 18 bungkus di rak
        $this->service->recordStockMovement($itemId, 18.0, 'opname', 'Stok Opname Akhir Bulan');
        $this->assertEquals(18.0, $this->service->getStock($itemId));

        // Adjustment karena 2 bungkus rusak terkena air (-2)
        $this->service->recordStockMovement($itemId, -2.0, 'adjustment', 'Barang rusak terkena air');
        $this->assertEquals(16.0, $this->service->getStock($itemId));
    }

    public function testLowStockAlert(): void
    {
        $this->tenantContext->setTenantId('1');

        $itemSafe = $this->service->createItem([
            'name' => 'Betadine 30ml',
            'initial_stock' => 50.0,
            'min_stock_alert' => 10.0,
        ]);

        $itemLow = $this->service->createItem([
            'name' => 'Alkohol 70% 1 Liter',
            'initial_stock' => 3.0,
            'min_stock_alert' => 5.0,
        ]);

        $lowItems = $this->service->listLowStockItems();
        $this->assertCount(1, $lowItems);
        $this->assertSame($itemLow, $lowItems[0]['id']);
        $this->assertSame('Alkohol 70% 1 Liter', $lowItems[0]['name']);
    }

    public function testLookupByCodeAndBarcode(): void
    {
        $this->tenantContext->setTenantId('1');

        $itemId = $this->service->createItem([
            'name' => 'Termometer Digital',
            'code' => 'ITM-THM-01',
            'barcode' => '8999888777666',
        ]);

        $byCode = $this->service->getItemByCode('ITM-THM-01');
        $this->assertNotNull($byCode);
        $this->assertSame($itemId, $byCode['id']);

        $byBarcode = $this->service->getItemByBarcode('8999888777666');
        $this->assertNotNull($byBarcode);
        $this->assertSame($itemId, $byBarcode['id']);
    }

    public function testMultiTenantIsolation(): void
    {
        // Tenant 1
        $this->tenantContext->setTenantId('1');
        $itemT1 = $this->service->createItem([
            'name' => 'Stetoskop T1',
            'initial_stock' => 5.0,
        ]);

        // Tenant 2
        $this->tenantContext->setTenantId('2');
        $itemT2 = $this->service->createItem([
            'name' => 'Kunci Pas 12mm T2',
            'initial_stock' => 12.0,
        ]);

        // Tenant 2 tidak boleh dapat melihat atau memodifikasi item milik Tenant 1
        $this->assertNull($this->service->getItem($itemT1));
        $this->assertNotNull($this->service->getItem($itemT2));

        $t2Items = $this->service->searchItems('');
        $this->assertCount(1, $t2Items);
        $this->assertSame('Kunci Pas 12mm T2', $t2Items[0]['name']);
    }

    public function testGlobalItemsAndInventoryHelpers(): void
    {
        $this->tenantContext->setTenantId('1');
        $this->assertInstanceOf(InventoryRegistryInterface::class, items());
        $this->assertInstanceOf(InventoryRegistryInterface::class, inventory());
    }
}
